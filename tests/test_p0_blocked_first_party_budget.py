def test_a_healthy_origin_behaves_exactly_as_before(tmp_path):
    report, calls = run_live(
        tmp_path,
        first_party_items=[first_party(n) for n in range(8)],
        third_party_items=[third_party(n) for n in range(8)],
        probe=lambda article, call_no: None,  # every dossier is deployed
        scheduler="real",
    )
    assert report["published"] == 4
    assert report["source_delivery_blocked"] == 0
    assert report["source_delivery_circuit_open"] is False
    assert len(calls["transform"]) <= _publication_attempt_limit(4)


def test_a_dossier_that_resolves_proves_the_origin_is_serving_and_resets_the_counter(tmp_path):
    # 404, 404, then a dossier that resolves: three 404s are never CONSECUTIVE, so nothing is skipped unprobed.
    report, calls = run_live(
        tmp_path,
        first_party_items=[first_party(n) for n in range(8)],
        third_party_items=[third_party(n) for n in range(8)],
        probe=lambda article, call_no: NOT_DEPLOYED if call_no <= 2 else None,
    )
    assert report["source_delivery_circuit_open"] is False
    assert report["published"] == 4
    assert len(fp_probes(calls)) >= 3  # the later first-party dossiers were each really probed


def test_per_item_content_problems_never_open_the_circuit_and_the_work_stays_bounded(tmp_path):
    # A title mismatch is about ONE dossier: no circuit. Blocked items stop burning the LLM attempt budget, but the
    # number of candidates examined stays bounded (attempt budget + relief slots = 12).
    report, calls = run_live(
        tmp_path,
        first_party_items=[first_party(n) for n in range(20)],
        third_party_items=[third_party(n) for n in range(8)],
        retry_first_party=[first_party(n) for n in range(100, 108)],
        probe=lambda article, call_no: "first_party_source_title_mismatch" if is_fp(article.url) else None,
    )
    assert report["source_delivery_circuit_open"] is False
    assert len(fp_probes(calls)) <= 12
    assert len(calls["transform"]) <= _publication_attempt_limit(4)


@pytest.mark.parametrize("reason", ["first_party_source_unreachable", "first_party_source_http_503"])
def test_an_origin_outage_is_handled_like_a_missing_deployment(tmp_path, reason):
    report, calls = run_live(
        tmp_path,
        first_party_items=[first_party(n) for n in range(8)],
        third_party_items=[third_party(n) for n in range(8)],
        retry_first_party=[first_party(n) for n in range(100, 108)],
        probe=lambda article, call_no: reason if is_fp(article.url) else None,
    )
    assert report["published"] == 4
    assert report["source_delivery_circuit_open"] is True
    assert len(fp_probes(calls)) <= 3
