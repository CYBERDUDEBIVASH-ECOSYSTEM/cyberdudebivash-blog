"""P0 regression: blocked first-party SOC items must not starve deliverable third-party reports.

Incident (2026-11-24, CTI Blogger runs 9306 and 9307): published posts per run fell 4, 1, 0. The scheduler ranks
first-party SOC dossiers first, and every one of them failed the public-delivery probe with HTTP 404 (the live SOC
Worker predates them). Each blocked item still consumed one of the 6 publication ATTEMPTS, a budget whose purpose
(see _publication_attempt_limit) is to bound LLM/API work, although the probe runs before any hydration or LLM
work. All 6 attempts went to blocked items, so none of the ~150 other candidates was ever tried.

These tests drive the real run_pipeline live loop and the real scheduler. Only the network, the transformer, the
publisher and the side-effect services are replaced.
"""
import os
from collections import Counter
from contextlib import ExitStack
from datetime import datetime, timezone
from types import SimpleNamespace
from unittest.mock import patch

import pytest

from automation.config import Config
from automation.content_discovery import ContentDiscoveryEngine, DiscoveredArticle
from automation.main import run_pipeline, _publication_attempt_limit
from automation.publication_scheduler import PublicationSelection
from automation.report_integrity import PublicationIntegrityError, compute_artifact_hash

NOW = datetime.now(timezone.utc).isoformat()
NOT_DEPLOYED = "first_party_source_http_404"


def first_party(n):
    cve = f"CVE-2026-1{n:05d}"
    return DiscoveredArticle(
        url=f"https://blog.cyberdudebivash.in/posts/{cve.lower()}.html",
        title=f"{cve} — Affected software (product not identified) CVSS 9.{n % 10} Critical Vulnerability",
        summary="Critical vulnerability record generated by the SOC pipeline.",
        published_at=NOW,
        content_hash=f"fp{n:04d}",
        labels=["CYBERDUDEBIVASH", "Threat Intelligence", "Vulnerabilities"],
        source="rss",
        source_publisher="CYBERDUDEBIVASH",
        cve_id=cve,
        cvss_score=9.0 + (n % 10) / 10,
    )


def third_party(n):
    return DiscoveredArticle(
        url=f"https://news.example.test/story-{n}",
        title=f"Researchers disclose a backdoor in widely used package number {n}",
        summary="Attackers abused a maintainer account to publish a trojanised release that steals credentials.",
        published_at=NOW,
        content_hash=f"tp{n:04d}",
        labels=["CYBERDUDEBIVASH", "Threat Intelligence"],
        source="global_rss",
        source_publisher="Example News",
    )


def make_config(tmp_path, max_posts=4):
    cfg = Config()
    cfg.blogger_client_id = "test-client-id"
    cfg.blogger_client_secret = "test-secret"
    cfg.blogger_refresh_token = "test-refresh"
    cfg.blogger_blog_id = "test-blog-id"
    cfg.anthropic_api_key = ""
    cfg.state_file = os.path.join(str(tmp_path), "state.json")
    cfg.logs_dir = os.path.join(str(tmp_path), "logs")
    cfg.max_posts_per_run = max_posts
    cfg.retry_attempts = 2
    cfg.retry_base_delay = 0.01
    return cfg


def first_party_first_scheduler(retry, fresh, max_posts):
    """Stand-in for the production ranking observed in runs 9306 and 9307 (selected_sources {'rss': 5-6}): the
    scheduler picks first-party SOC dossiers first, from the persisted retry queue and the fresh pool, for the
    initial batch AND for every quality backfill. How the real scheduler ranks is not what this change alters."""
    pool = [(a, "retry") for a in retry] + [(a, "fresh") for a in fresh]
    pool.sort(key=lambda pair: 0 if is_fp(pair[0].url) else 1)  # stable: retry stays ahead of fresh
    chosen = pool[:max(0, int(max_posts or 0))]
    articles = [a for a, _ in chosen]
    return PublicationSelection(articles, {
        "candidate_count": len(pool), "fresh_candidates": len(fresh), "retry_candidates": len(retry),
        "fresh_selected": sum(1 for _, kind in chosen if kind == "fresh"),
        "retry_selected": sum(1 for _, kind in chosen if kind == "retry"),
        "strategic_selected": 0, "vulnerability_selected": sum(1 for a in articles if is_fp(a.url)),
        "canonical_selected": sum(1 for a in articles if is_fp(a.url)),
        "selected_families": dict(Counter("vulnerability" if is_fp(a.url) else "general" for a in articles)),
        "selected_sources": dict(Counter(a.source for a in articles)),
        "non_intelligence_filtered": 0,
    })


def run_live(tmp_path, *, first_party_items, third_party_items, probe, max_posts=4, transform_fails_for=(), retry_first_party=(), scheduler="fp_first"):
    """One live run. Returns (report, calls) where calls records what actually happened."""
    calls = {"probe": [], "transform": [], "publish": []}

    def fake_probe(article, **_kw):
        calls["probe"].append(article.url)
        return probe(article, len(calls["probe"]))

    class FakeTransformer:
        def __init__(self, config):
            pass

        def transform(self, article):
            calls["transform"].append(article.url)
            if article.source in transform_fails_for:
                raise PublicationIntegrityError(["test quality block"])
            content = f"<p>{article.title}</p>"
            return {
                "title": article.title, "content": content, "labels": ["CYBERDUDEBIVASH"],
                "content_source": "test", "llm_attempts": [], "image_url": None,
                "certified_artifact_hash": compute_artifact_hash(content),
            }

    class FakePublisher:
        def __init__(self, config):
            pass

        def publish_post(self, title, content, labels, is_draft=False, image_url=None):
            calls["publish"].append(title)
            n = len(calls["publish"])
            return {"id": f"post-{n}", "url": f"https://cti.example.test/post-{n}.html"}

    class FakeSubmitter:
        def __init__(self, config):
            pass

        def submit_url(self, url):
            return True

    class FakeAmplifier:
        def __init__(self, config):
            pass

        def amplify(self, payload):
            return {}

    def no_network(*_a, **_k):
        raise AssertionError("unexpected network call in a unit-level pipeline test")

    with ExitStack() as stack:
        enter = stack.enter_context
        enter(patch("automation.main.discover_local_canonical_rss", return_value=list(first_party_items)))
        enter(patch.object(ContentDiscoveryEngine, "discover", return_value=list(third_party_items)))
        enter(patch("automation.main.original_source_is_current", lambda *a, **k: True))
        if scheduler == "fp_first":
            enter(patch("automation.main.select_publication_batch", first_party_first_scheduler))
        enter(patch("automation.main.verify_public_first_party_source", fake_probe))
        enter(patch("automation.main.hydrate_selected_article", lambda article: SimpleNamespace(
            attempted=False, adopted=False, reason="test", before_words=0, after_words=0)))
        enter(patch("automation.main.AuthorityTransformer", FakeTransformer))
        enter(patch("automation.main.BloggerPublisher", FakePublisher))
        enter(patch("automation.main.fetch_back_and_verify", lambda *a, **k: SimpleNamespace(
            verified=True, defects=(), to_dict=lambda: {"verified": True})))
        enter(patch("automation.main.SearchConsoleSubmitter", FakeSubmitter))
        enter(patch("automation.main.SocialAmplifier", FakeAmplifier))
        enter(patch("time.sleep"))
        enter(patch("requests.get", no_network))
        enter(patch("requests.post", no_network))
        cfg = make_config(tmp_path, max_posts)
        if retry_first_party:
            # The scheduler selects the persisted retry queue FIRST. In production it holds the first-party SOC items
            # that were blocked in the previous run, so they are selected, and blocked, again every hour.
            seeded = ContentDiscoveryEngine(cfg).state
            for item in retry_first_party:
                seeded.add_to_retry_queue(item, "Publication blocked: first-party SOC public source not deliverable")
        report = run_pipeline(cfg, dry_run=False)
    return report, calls


def is_fp(url):
    return "blog.cyberdudebivash.in/posts/" in url


def fp_probes(calls):
    """Network probes that actually go to the SOC origin (the check is a no-op for third-party items)."""
    return [u for u in calls["probe"] if is_fp(u)]


def always_not_deployed(article, call_no):
    return NOT_DEPLOYED if is_fp(article.url) else None


# ---------------------------------------------------------------------------------------------------------------
def test_the_incident_third_party_reports_still_publish_while_every_first_party_dossier_is_not_deployed(tmp_path):
    report, calls = run_live(
        tmp_path,
        first_party_items=[first_party(n) for n in range(8)],
        third_party_items=[third_party(n) for n in range(8)],
        retry_first_party=[first_party(n) for n in range(100, 108)],
        probe=always_not_deployed,
    )
    assert report["published"] == 4, "a deliverable third-party report must publish while SOC dossiers 404"
    assert not any(is_fp(u) for u in calls["transform"]), "no first-party item may reach the LLM/transform stage"
    assert report["source_delivery_blocked"] >= 3
    # the cheap probe is bounded: after 3 consecutive "not deployed" answers the origin is treated as not serving
    assert len(fp_probes(calls)) <= 3
    assert report["source_delivery_circuit_open"] is True
    assert report["source_delivery_probes_skipped"] >= 1, "later first-party items are blocked without another request"


def test_expensive_work_stays_bounded_by_the_original_attempt_budget(tmp_path):
    # Third-party items failing their own quality gate DO consume attempts, exactly as before.
    report, calls = run_live(
        tmp_path,
        first_party_items=[first_party(n) for n in range(8)],
        third_party_items=[third_party(n) for n in range(30)],
        retry_first_party=[first_party(n) for n in range(100, 108)],
        probe=always_not_deployed,
        transform_fails_for=("global_rss",),
    )
    assert report["published"] == 0
    assert len(calls["transform"]) <= _publication_attempt_limit(4)  # 6: LLM/API work is still capped


def test_nothing_deliverable_at_all_still_ends_cleanly_with_a_bounded_number_of_probes(tmp_path):
    report, calls = run_live(
        tmp_path,
        first_party_items=[first_party(n) for n in range(40)],
        third_party_items=[],
        retry_first_party=[first_party(n) for n in range(100, 108)],
        probe=always_not_deployed,
    )
    assert report["published"] == 0
    assert len(fp_probes(calls)) <= 3
    assert report["failed"] == report["integrity_blocked"]  # nothing else went wrong; the run ends, it does not loop


